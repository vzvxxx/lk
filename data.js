/* Функция — именованное действие, которое можно вызвать.
   getProfile ("получить профиль") — отдаёт объект profile тому, кто попросил.
   return ("вернуть") — что именно отдать.

   Перед выдачей кладём в профиль цитату из списка.
   const запрещает переназначить само имя profile,
   но менять поля ВНУТРИ объекта не запрещает. */

async function getProfile() {
  const today = new Date();                        // сегодняшняя дата

  /* Первое января этого года.
     Внимание: месяцы нумеруются с НУЛЯ, поэтому январь — это 0. */
  const yearStart = new Date(today.getFullYear(), 0, 1);

  /* Разница двух дат даёт МИЛЛИСЕКУНДЫ, а не дни.
     Делим на количество миллисекунд в сутках: 24 часа x 60 минут x 60 секунд x 1000.
     Math.floor — округлить вниз, отбросить дробную часть.
     +1 — чтобы 1 января был днём номер 1, а не 0. */
  const msInDay   = 24 * 60 * 60 * 1000;
  const dayOfYear = Math.floor((today - yearStart) / msInDay) + 1;

  const index = dayOfYear % quotes.length;   // остаток: всегда в пределах списка

  /* Собираем ответ из двух источников: то, что знает человек,
     и то, что выводится из выбранной группы.
     Object.assign({}, ...) — сделать новый объект, не трогая profile. */

  const group = await getGroup();

  return Object.assign({}, profile, {
    quote:     quotes[index],
    institute: scheduleInfo.faculty,
    year:      scheduleInfo.course,
    group:     group === "" ? "не выбрана" : group
  });
}


