/* getSchedule отдаёт расписание уже РАЗОБРАННЫМ: название без пометки,
   тип отдельным полем. Страница не знает, как тип был вычислен, —
   она получает готовый ответ. Это и есть граница из решения 2. */

async function getSchedule(group) {
  const dni = scheduleByGroup[group] || [];

  return dni.map(function (den) {
    return {
      name: den.name,
      lessons: den.lessons.map(function (para) {
        return Object.assign({}, para, {
          subject: ubratPometku(para.subject),
          type:    tipZanyatiya(den.name, para)
        });
      })
    };
  });
}

