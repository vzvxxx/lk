/* chistoeImya — убрать приклеенное к фамилии.

   В источнике попадается "асс Иванов А.А.434" — аудитория слиплась
   с именем. Отрезаем хвост из цифр и лишние пробелы. */

function chistoeImya(name) {
  let imya = String(name).trim();

  while (imya.length > 0 && imya[imya.length - 1] >= "0" && imya[imya.length - 1] <= "9") {
    imya = imya.slice(0, -1).trim();
  }

  return imya.split(" ").filter(Boolean).join(" ");
}


/* Звания, с которых начинается имя. Порядок важен: длинные раньше
   коротких, иначе "ст.преп" опознается как "преп", а "с.н.с" как "н.с". */

const ZVANIYA = ["ст.преп", "ст. преп", "с.н.с", "м.н.с", "в.н.с",
                 "н.с", "доц", "проф", "асс", "асп", "преп", "инж"];


/* klyuchImeni — по нему сводим варианты записи ОДНОГО человека.

   В источнике один и тот же преподаватель записан по-разному:
   у лекции полное имя, у семинара сокращённое, где-то пропущен пробел.

     проф. Асташова Ирина Викторовна  =  проф. Асташова И.В.
     доц. Салова Т.В.                 =  доц. Т.В. Салова
     проф. Гордиенко Алексей Сергеевич =  проф.Гордиенко А.С.

   Ключ — ФАМИЛИЯ и ОБА инициала. Звание отбрасывается: один и тот же
   человек у лекции "проф.", а у семинара может быть без звания.

   Почему оба инициала, а не один: на мехмате есть
   "проф. Шафаревич А.И." и "доц. Шафаревич А.А." — РАЗНЫЕ люди.
   По одному инициалу они склеивались в одного. */

function klyuchImeni(name) {
  let t = chistoeImya(name);

  /* отрезать звание в начале */
  for (const zvanie of ZVANIYA) {
    if (t.toLowerCase().startsWith(zvanie)) {
      t = t.slice(zvanie.length);

      while (t.length > 0 && (t[0] === "." || t[0] === " ")) {
        t = t.slice(1);
      }
      break;
    }
  }

  /* "В.Д." превращаем в "В. Д.", чтобы инициалы стали отдельными словами */
  const slova = t.split(".").join(". ").split(" ").filter(Boolean);

  let familiya = "";
  let initsialy = "";

  for (const slovo of slova) {
    const chistoe = slovo.split(".").join("");

    if (chistoe.length >= 3) {
      if (familiya === "") {
        familiya = chistoe;          /* длинное слово — фамилия */
      } else {
        initsialy = initsialy + chistoe[0];   /* имя или отчество целиком */
      }
    } else if (chistoe.length > 0) {
      initsialy = initsialy + chistoe[0];     /* инициал */
    }
  }

  return (familiya + "|" + initsialy.slice(0, 2)).toLowerCase();
}


/* getTeachers(group) — кто ведёт у этой группы.

   Возвращает список: имя, предметы, когда и где ведёт, адрес почты
   (если известен). Порядок — по алфавиту. */

async function getTeachers(group) {
  const dni = await getSchedule(group);
  const svodka = {};

  for (const den of dni) {
    for (const para of den.lessons) {
      const imya = chistoeImya(para.teacher);

      /* Прочерк у служебных блоков, "по подгруппам" у английского —
         это не имена людей. */
      if (imya === "" || imya === "—" || imya === "по подгруппам") {
        continue;
      }

      const klyuch = klyuchImeni(imya);

      if (svodka[klyuch] === undefined) {
        svodka[klyuch] = { name: imya, subjects: [], lessons: [] };
      }

      /* Из нескольких вариантов записи берём самый полный:
         "проф. Плотников Михаил Геннадьевич" вместо "Плотников М.Г." */
      if (imya.length > svodka[klyuch].name.length) {
        svodka[klyuch].name = imya;
      }

      if (!svodka[klyuch].subjects.includes(para.subject)) {
        svodka[klyuch].subjects.push(para.subject);
      }

      svodka[klyuch].lessons.push({
        day:  den.name,
        time: para.time,
        room: para.room,
        subject: para.subject,
        type: para.type,
        week: para.week
      });
    }
  }

  const spisok = Object.keys(svodka).map(function (klyuch) {
    const chelovek = svodka[klyuch];

    return {
      name:     chelovek.name,
      subjects: chelovek.subjects,
      lessons:  chelovek.lessons,
      email:    teacherEmails[chelovek.name] || ""
    };
  });

  spisok.sort(function (a, b) {
    return a.name.localeCompare(b.name, "ru");
  });

  return spisok;
}
