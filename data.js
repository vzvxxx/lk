/* ---------- ТИП ЗАНЯТИЯ: ЛЕКЦИЯ ИЛИ СЕМИНАР ---------- */

/* В источнике тип указан НЕ везде: помечено 74 пары из 492,
   и четырьмя разными способами. Остальные 418 без пометки —
   но это не значит "семинар": 111 из них стоят в лекционных залах.

   Поэтому подсказок две.

   ПЕРВАЯ — пометка в названии. Если она есть, верим ей.

   ВТОРАЯ — сколько групп слушают одно и то же в одно время
   в одной аудитории. Лекцию читают потоку, семинар идёт у одной
   группы. У нас есть все 22 группы, значит это можно посчитать.

   Порядок: пометка главнее счёта. Нет пометки — считаем группы:
   четыре и больше значит лекция.

   Часть подписей — ВЫВОД, а не факт из источника. Об этом честно
   сказано один раз в подписи над расписанием. */

const LEKCIA_POMETKI  = ["(л)", "(лекция)", ",лекция"];
const SEMINAR_POMETKI = ["(с)", "(семинар)", ",семинар"];


/* szhat ("сжать") — убрать пробелы и привести к строчным буквам.
   Нужно, потому что в источнике пишут и "Алгебра (л)", и "Алгебра(л)". */

function szhat(text) {
  return text.split(" ").join("").toLowerCase();
}


/* estPometka — заканчивается ли название одной из пометок списка. */

function estPometka(subject, spisok) {
  const konec = szhat(subject);

  for (const pometka of spisok) {
    if (konec.endsWith(pometka)) {
      return true;
    }
  }
  return false;
}


/* ubratPometku — вернуть название без пометки.
   "Алгебра (л)" -> "Алгебра". Пометку показываем отдельной плашкой,
   поэтому в названии она больше не нужна. */

function ubratPometku(subject) {
  for (const znak of ["(", ","]) {
    const mesto = subject.lastIndexOf(znak);

    if (mesto > 0) {
      const hvost = szhat(subject.slice(mesto));

      if (LEKCIA_POMETKI.includes(hvost) || SEMINAR_POMETKI.includes(hvost)) {
        return subject.slice(0, mesto).trim();
      }
    }
  }
  return subject;
}


/* Счёт групп считается ОДИН раз, при первом вопросе, и запоминается.
   null означает "ещё не считали". */

let potoki = null;

function klyuchPary(den, para) {
  return den + "|" + para.time + "|" + szhat(ubratPometku(para.subject)) + "|" + para.room;
}

function poschitatPotoki() {
  const schet = {};

  for (const gruppa of Object.keys(scheduleByGroup)) {
    for (const den of scheduleByGroup[gruppa]) {
      for (const para of den.lessons) {
        const klyuch = klyuchPary(den.name, para);

        if (schet[klyuch] === undefined) {
          schet[klyuch] = [];
        }
        if (!schet[klyuch].includes(gruppa)) {
          schet[klyuch].push(gruppa);
        }
      }
    }
  }
  return schet;
}


/* tipZanyatiya — "лекция", "семинар" или пустая строка.

   Пустая строка у служебных блоков: физвоспитание, межфакультетские
   курсы, день самостоятельной работы. У них нет ни преподавателя,
   ни аудитории, и подписывать их нечем. Тот же приём, что везде
   в проекте: нет данных — нет и упоминания. */

function tipZanyatiya(denName, para) {
  if (para.room === "—") {
    return "";
  }

  /* Занятие с подгруппами лекцией быть не может: у каждой подгруппы
     свой преподаватель и своя аудитория. Проверка стоит ДО счёта групп
     нарочно — иначе счёт ошибается. У английского аудитория записана
     словами "по подгруппам", строка у всех групп одинаковая,
     и счёт принимал его за поток. */
  if (para.details !== undefined) {
    return "семинар";
  }

  if (estPometka(para.subject, LEKCIA_POMETKI)) {
    return "лекция";
  }

  if (estPometka(para.subject, SEMINAR_POMETKI)) {
    return "семинар";
  }

  if (potoki === null) {
    potoki = poschitatPotoki();
  }

  const gruppy = potoki[klyuchPary(denName, para)] || [];

  if (gruppy.length >= 4) {
    return "лекция";
  }
  return "семинар";
}


